#!/usr/bin/env python3
"""Writes the MPEG audio tables the Layer III entropy pass and the decoder use, from the minimp3 in third_party/minimp3, so they are not typed in by hand:

    python3 scripts/fixtures/mpeg_tables.py            writes the files
    python3 scripts/fixtures/mpeg_tables.py --check    fails if a committed file differs

minimp3 (CC0 1.0, commit ea99364f, third_party/README.md) holds the 34 Huffman tables of ISO/IEC 11172-3 Annex B in its compact form
(`tabs`, `tab32`, `tab33`, `tabindex`, `g_linbits`), the scalefactor band widths of the eight sample rates (`g_scf_long`, `g_scf_short`,
`g_scf_mixed`), the partitions of the MPEG-2 scalefactors and the polyphase window's integer coefficients (`g_win`). They are format
data: the standard defines them, and minimp3 is the only source at hand that holds them.

  src/Encspect.Formats.Mpeg/Layer3Tables.Data.cs    the tables the parser's entropy pass reads (integers)
  src/Encspect.Formats.Mpeg/Decoding/SynthesisTables.cs   the window and the transform constants the decoder computes with (floats, as minimp3 states them)
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "third_party" / "minimp3" / "minimp3.h"
PARSER_OUT = ROOT / "src" / "Encspect.Formats.Mpeg" / "Layer3Tables.Data.cs"
DECODER_OUT = ROOT / "src" / "Encspect.Formats.Mpeg" / "Decoding" / "SynthesisTables.cs"

NOTICE = """// Generated by scripts/fixtures/mpeg_tables.py from minimp3 (https://github.com/lieff/minimp3, commit ea99364f), which its authors dedicated to the
// public domain (CC0 1.0, third_party/minimp3/LICENSE). Do not edit by hand."""


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def array(text, name):
    """The numbers of the C array called name as written (flattened), in order."""
    match = re.search(r"\b" + re.escape(name) + r"\s*(\[[^\]]*\])+\s*=\s*\{(.*?)\};", text, flags=re.S)
    if match is None:
        raise SystemExit(f"{name} not found in {SOURCE}")
    body = re.sub(r"[{}]", " ", match.group(2))
    return [token.strip() for token in body.replace("\n", " ").split(",") if token.strip()]


def rows(values, width):
    for start in range(0, len(values), width):
        yield values[start:start + width]


def emit_ints(name, values, element, comment, per_line=24):
    lines = [f"    // {comment}", f"    internal static readonly {element}[] {name} ="]
    lines.append("    [")
    for row in rows(values, per_line):
        lines.append("        " + ", ".join(row) + ",")
    lines.append("    ];")
    return "\n".join(lines)


def emit_floats(name, values, comment, per_line=8):
    values = [v if v.endswith("f") else v + "f" for v in values]
    return emit_ints(name, values, "float", comment, per_line)


def parser_file(text):
    tabs = array(text, "tabs")
    out = [NOTICE, "", "namespace Encspect.Formats.Mpeg;", "",
           "// The Layer III tables of the entropy pass (ISO/IEC 11172-3 Annex B and 2.4.3.4), in minimp3's compact form.", "internal static partial class Layer3Tables", "{"]
    out.append(emit_ints("Codebooks", tabs, "short", f"The Huffman tables 1 to 31 as minimp3 packs them: a leaf is (code length << 8) | the two values (4 bits each); a negative entry points to a second level ({len(tabs)} entries)."))
    out.append("")
    out.append(emit_ints("Count1Table0", array(text, "tab32"), "byte", "The count1 table A (ISO/IEC 11172-3 Table B.7, tab32)."))
    out.append("")
    out.append(emit_ints("Count1Table1", array(text, "tab33"), "byte", "The count1 table B (Table B.8, tab33): four-bit codes of the inverted values."))
    out.append("")
    out.append(emit_ints("TableOffsets", array(text, "tabindex"), "short", "Where the codebook of each of the 32 table_select values starts in Codebooks."))
    out.append("")
    out.append(emit_ints("LinBits", array(text, "g_linbits"), "byte", "The extra bits (linbits) of each table_select value."))
    out.append("")
    scf_long = array(text, "g_scf_long")
    out.append(emit_ints("LongBands", scf_long, "byte", "The widths of the long-block scalefactor bands (Table B.8 of ISO/IEC 11172-3 and 13818-3) of the eight sample rate rows, 23 entries each, a 0 ends a row.", 23))
    out.append("")
    out.append(emit_ints("ShortBands", array(text, "g_scf_short"), "byte", "The short-block bands, each width three times (one per window), 40 entries a row.", 40))
    out.append("")
    out.append(emit_ints("MixedBands", array(text, "g_scf_mixed"), "byte", "The mixed-block bands: the long bands below the switch point, then the short ones, 40 entries a row.", 40))
    out.append("")
    out.append(emit_ints("Partitions", array(text, "g_scf_partitions"), "byte", "The scalefactor band partitions of MPEG-2 and 2.5 (ISO/IEC 13818-3 Table nr_of_sfb_block), 28 entries a row.", 28))
    out.append("")
    out.append(emit_ints("Moduli", array(text, "g_mod"), "byte", "The moduli that split an MPEG-2 scalefac_compress into slen values, four per partition set.", 12))
    out.append("")
    out.append(emit_ints("Mpeg1SlenCode", array(text, "g_scfc_decode"), "byte", "MPEG-1 scalefac_compress as slen1 * 4 + slen2 (ISO/IEC 11172-3 Table 3-B.6 style code)."))
    out.append("}")
    return "\n".join(out) + "\n"


def decoder_file(text):
    out = [NOTICE, "", "namespace Encspect.Formats.Mpeg.Decoding;", "",
           "// The window and transform constants of the Layer III and polyphase stages, exactly as minimp3 states them.", "internal static class SynthesisTables", "{"]
    window = array(text, "g_win")
    out.append(emit_ints("Window", window, "int", f"The integer coefficients of the polyphase synthesis window ({len(window)} entries, ISO/IEC 11172-3 Table 3-B.3 scaled by 2^16 and folded as minimp3 lays them out)."))
    out.append("")
    out.append(emit_floats("Antialias", array(text, "g_aa"), "The antialias butterfly coefficients: cs[0..7], then ca[0..7] (ISO/IEC 11172-3 Table 3-B.9)."))
    out.append("")
    out.append(emit_floats("Twiddle9", array(text, "g_twid9"), "The 36-point inverse transform's twiddle factors."))
    out.append("")
    out.append(emit_floats("Twiddle3", array(text, "g_twid3"), "The 12-point inverse transform's twiddle factors."))
    out.append("")
    out.append(emit_floats("MdctWindow", array(text, "g_mdct_window"), "The long window (36 points, folded to 18) and the stop window.", 9))
    out.append("")
    out.append(emit_floats("SecantFactors", array(text, "g_sec"), "The 32-point DCT-II's secant factors."))
    out.append("")
    out.append(emit_floats("PanFactors", array(text, "g_pan"), "MPEG-1 intensity stereo positions: left and right gain for is_pos 0 to 6 (ISO/IEC 11172-3 2.4.3.4.9.3)."))
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    text = strip_comments(SOURCE.read_text())
    wanted = {PARSER_OUT: parser_file(text), DECODER_OUT: decoder_file(text)}
    failed = False
    for path, content in wanted.items():
        if check:
            if not path.exists() or path.read_text() != content:
                print(f"{path.relative_to(ROOT)} differs from what mpeg_tables.py writes", file=sys.stderr)
                failed = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
