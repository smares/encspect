FIXTURES = {}
VERSION = struct.pack(">I", 2726318400)


def fixture(name, data, findings=(), stream=True, base=0, extension="aiff"):
    FIXTURES[name] = (data, [(f, 1) if isinstance(f, str) else f for f in findings], stream, base, extension)


def sound(frames=50, channels=2, bits=16, rate=44100):
    return pcm(rate, channels, frames, bits)


def basic(frames=50, channels=2, bits=16, rate=44100, **kw):
    return [chunk("COMM", comm(channels, frames, bits, rate, **kw)), chunk("SSND", ssnd(sound(frames, channels, bits, rate)))]


def aifc(chunks, size=None):
    return form([chunk("FVER", VERSION), *chunks], b"AIFC", size)


def text(value, size):
    return value.encode("latin1")[:size].ljust(size, b"\0")


def id3v2(frames):
    body = b""
    for fid, value in frames:
        payload = b"\x00" + value.encode("latin1")
        body += fid.encode() + struct.pack(">I", len(payload)) + b"\x00\x00" + payload
    size = len(body)
    return b"ID3\x03\x00\x00" + bytes([(size >> 21) & 0x7F, (size >> 14) & 0x7F, (size >> 7) & 0x7F, size & 0x7F]) + body


def id3v1(title="Title"):
    return b"TAG" + text(title, 30) + text("Artist", 30) + text("Album", 30) + b"2026" + text("", 28) + b"\x00\x01" + b"\x11"


def marker(mid, position, name):
    return struct.pack(">hI", mid, position) + pstring(name)


def comment(stamp, mid, value):
    raw = value.encode("latin1")
    return struct.pack(">IhH", stamp, mid, len(raw)) + raw + (b"\0" if len(raw) % 2 else b"")


def loop(mode, begin, end):
    return struct.pack(">hhh", mode, begin, end)


