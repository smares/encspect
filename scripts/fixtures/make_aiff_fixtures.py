def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for pattern in ("built-*.aiff", "built-*.aifc"):
        for old in OUT.glob(pattern):
            old.unlink()
    for name, (data, findings, stream, base, extension) in sorted(FIXTURES.items()):
        (OUT / f"{name}.{extension}").write_bytes(data)
        try:
            manifest = m.manifest(data, base)
        except ValueError:
            manifest = {"length": len(data), "container": None, "chunks": [], "stream": None}
        if not stream:
            manifest["stream"] = None
        manifest["findings"] = [{"code": code, **({"count": count} if count != 1 else {})} for code, count in findings]
        (OUT / f"{name}.expected.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    print(f"{len(FIXTURES)} fixtures written")


if __name__ == "__main__":
    main()
