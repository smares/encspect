"""Writes the hand-built AIFF fixtures in tests/fixtures/aiff (built-*.aiff, built-*.aifc) and their manifests.

Every byte is placed by this script (standard library only), from Apple's AIFF 1.3 and AIFF-C specifications: well-formed files of both form types
(every compression type the analyzer names, sample rates that need the whole of the 80-bit extended number, markers, comments, an instrument, text and
application chunks, block-aligned sound data, ID3v2 chunks) and files with one fault each (sizes, pad bytes, missing or repeated chunks, bad fields,
cuts). Each manifest states the chunks (worked out by aiff_model.py), the stream and exactly the findings the analyzer must raise, by the fault the
file was built with. Fixtures are regenerated byte for byte in CI.

    python3 scripts/fixtures/make_aiff_fixtures.py
"""

