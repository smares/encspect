#!/usr/bin/env python3
"""Writes and checks the codebooks of the Speex decoder from libspeex 1.2.1's BSD sources.

    speex_tables.py --write   writes src/Encspect.Formats.Speex/Decoding/SpeexTables.cs from the pinned archive
    speex_tables.py --check   fails where the committed file differs from what --write would produce

The tables are format data (the line spectral pair codebooks, the pitch gain codebooks and the innovation shape codebooks of the narrowband and wideband layers) that
libspeex defines and that have no other public source (docs/development.md, "Where the format tables come from"); each generated table names its source file and C name.
Only files under libspeex/ are read. The check that a table is right is the comparison of the decoder's PCM with libspeex's fixed-point build
(scripts/fixtures/crosscheck_speex_pcm.py): a wrong entry shows in the audio.
"""

import pathlib
import re
import sys
import tarfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import downloads  # noqa: E402
import speex_tool  # noqa: E402

ROOT = HERE.parents[1]
OUTPUT = ROOT / "src" / "Encspect.Formats.Speex" / "Decoding" / "SpeexTables.cs"
CACHE = ROOT / ".cache" / "speex-tables"

# (source file, C name, C# name, what it is). Every table is an array of signed char.
TABLES = [
    ("lsp_tables_nb.c", "cdbk_nb", "LspNarrowband", "10 values of each of 64 vectors: the first stage of the narrowband LSP quantizer, in units of 1/256"),
    ("lsp_tables_nb.c", "cdbk_nb_low1", "LspNarrowbandLow1", "5 values of each of 64 vectors: the lower half's second stage, in units of 1/512"),
    ("lsp_tables_nb.c", "cdbk_nb_low2", "LspNarrowbandLow2", "5 values of each of 64 vectors: the lower half's third stage, in units of 1/1024"),
    ("lsp_tables_nb.c", "cdbk_nb_high1", "LspNarrowbandHigh1", "5 values of each of 64 vectors: the upper half's second stage, in units of 1/512"),
    ("lsp_tables_nb.c", "cdbk_nb_high2", "LspNarrowbandHigh2", "5 values of each of 64 vectors: the upper half's third stage, in units of 1/1024"),
    ("high_lsp_tables.c", "high_lsp_cdbk", "LspHigh1", "8 values of each of 64 vectors: the first stage of the wideband layers' LSP quantizer, in units of 1/256"),
    ("high_lsp_tables.c", "high_lsp_cdbk2", "LspHigh2", "8 values of each of 64 vectors: its second stage, in units of 1/512"),
    ("gain_table.c", "gain_cdbk_nb", "PitchGainNarrowband", "4 values of each of 128 entries: the three pitch predictor taps (the fourth is unused)"),
    ("gain_table_lbr.c", "gain_cdbk_lbr", "PitchGainLowRate", "4 values of each of 32 entries: the three pitch predictor taps of the low-rate submodes"),
    ("exc_10_16_table.c", "exc_10_16_table", "Excitation10x16", "10 values of each of 16 shapes"),
    ("exc_10_32_table.c", "exc_10_32_table", "Excitation10x32", "10 values of each of 32 shapes"),
    ("exc_20_32_table.c", "exc_20_32_table", "Excitation20x32", "20 values of each of 32 shapes"),
    ("exc_5_64_table.c", "exc_5_64_table", "Excitation5x64", "5 values of each of 64 shapes"),
    ("exc_5_256_table.c", "exc_5_256_table", "Excitation5x256", "5 values of each of 256 shapes"),
    ("exc_8_128_table.c", "exc_8_128_table", "Excitation8x128", "8 values of each of 128 shapes"),
    ("hexc_10_32_table.c", "hexc_10_32_table", "HighExcitation10x32", "10 values of each of 32 shapes of the wideband layers' low-rate submode"),
    ("hexc_table.c", "hexc_table", "HighExcitation8x128", "8 values of each of 128 shapes of the wideband layers"),
]


def source_files():
    path = CACHE / speex_tool.NAME
    CACHE.mkdir(parents=True, exist_ok=True)
    downloads.fetch(speex_tool.ADDRESSES, speex_tool.SHA256, path)
    files = {}
    with tarfile.open(path) as tar:
        for member in tar.getmembers():
            if member.isfile() and "/libspeex/" in member.name and member.name.endswith(".c"):
                files[member.name.rsplit("/", 1)[1]] = tar.extractfile(member).read().decode("latin-1")
    return files


def values(text, name):
    found = re.search(r"const signed char " + re.escape(name) + r"\[(\d+)\]\s*=\s*\{(.*?)\};", text, re.S)
    if found is None:
        raise SystemExit(f"{name} not found")
    body = re.sub(r"/\*.*?\*/", "", found.group(2), flags=re.S)
    numbers = [int(x) for x in re.findall(r"-?\d+", body)]
    if len(numbers) != int(found.group(1)):
        raise SystemExit(f"{name}: {len(numbers)} values, declared {found.group(1)}")
    return numbers


def generate(files):
    lines = [
        f"// Generated by scripts/fixtures/speex_tables.py from libspeex {speex_tool.NAME.removeprefix('speex-').removesuffix('.tar.gz')} ({speex_tool.SHA256}).",
        "// The tables are format data of the Speex decoder (codebooks of the line spectral pairs, the pitch gains and the innovation shapes), copyright (c) 2002-2008 Jean-Marc Valin",
        "// and Xiph.org Foundation and the other holders named in libspeex's COPYING (the notice of the BSD 3-clause license is in THIRD-PARTY-NOTICES.md). Each table names its",
        "// source file and C name; the decoder documents what each element means.",
        "",
        "namespace Encspect.Formats.Speex.Decoding;",
        "",
        "internal static class SpeexTables",
        "{",
    ]
    for index, (file, name, csharp, what) in enumerate(TABLES):
        numbers = values(files[file], name)
        lines.append(f"    // libspeex {file}, {name}: {len(numbers)} values, {what}.")
        lines.append(f"    public static ReadOnlySpan<sbyte> {csharp} => new sbyte[]")
        lines.append("    {")
        for start in range(0, len(numbers), 16):
            lines.append("        " + ", ".join(str(n) for n in numbers[start:start + 16]) + ",")
        lines.append("    };")
        if index + 1 < len(TABLES):
            lines.append("")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 2 or argv[1] not in ("--write", "--check"):
        print(__doc__)
        return 2
    text = generate(source_files())
    if argv[1] == "--write":
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
        print(f"{OUTPUT} differs from what {pathlib.Path(__file__).name} --write produces")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
