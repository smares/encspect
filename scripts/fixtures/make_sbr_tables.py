#!/usr/bin/env python3
"""Writes, or with --check compares, src/Encspect.Formats.Aac/Decoding/SbrTableData.cs from libxaac (github.com/ittiam-systems/libxaac at 2fbadd5, Apache License 2.0):
the QMF prototype filter (esbr_qmf_c in decoder/ixheaacd_sbr_rom.c, 31-bit integers, divided by 2^31) and the table of noise phases (ixheaac_random_phase in
common/ixheaac_esbr_rom.c).

    python3 -I scripts/fixtures/make_sbr_tables.py [--check] <libxaac checkout>

Both are format data of ISO/IEC 14496-3 4.6.18 and 4.A (the prototype filter c[n], n = 0 to 639, and the noise table V of 512 complex values); the specification is not freely
available, so the check against libxaac's own copies is the one the repository has. The file is also pinned by a hash in AacSbrTablesTests."""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "src/Encspect.Formats.Aac/Decoding/SbrTableData.cs"


def lines_of(values):
    return ["        " + ", ".join(values[i:i + 6]) + "," for i in range(0, len(values), 6)]


def qmf(root):
    source = (root / "decoder/ixheaacd_sbr_rom.c").read_text()
    at = source.index("esbr_qmf_c[1280] =")
    body = source[source.index("{", at) + 1:]
    body = body[:body.index("}")]
    numbers = [int(t) for t in re.findall(r"-?\d+", re.sub(r"/\*.*?\*/|//[^\n]*", "", body, flags=re.S))]
    if len(numbers) != 1280:
        sys.exit(f"{len(numbers)} values in esbr_qmf_c where 1280 were expected")
    # The array lists the 640 values twice (its two halves are equal, which the check requires).
    if numbers[:640] != numbers[640:]:
        sys.exit("the two halves of esbr_qmf_c differ")
    return [repr(n / 2 ** 31) + "f" for n in numbers[:640]]


def noise(root):
    source = (root / "common/ixheaac_esbr_rom.c").read_text()
    at = source.index("ixheaac_random_phase[512][2] =")
    body = source[source.index("{", at):]
    body = body[:body.index("};")]
    values = re.findall(r"-?\d+\.\d+f", body)
    if len(values) != 1024:
        sys.exit(f"{len(values)} values in ixheaac_random_phase where 1024 were expected")
    return [repr(float(v[:-1])) + "f" for v in values]


def render(root):
    out = [
        "// Generated by scripts/fixtures/make_sbr_tables.py. Format data of ISO/IEC 14496-3 4.6.18: the QMF prototype filter (c[n] for n = 0 to 639) and the table of noise phases (V, 512 complex values).",
        "// Taken from libxaac (github.com/ittiam-systems/libxaac at 2fbadd5, Apache License 2.0, Copyright (C) The Android Open Source Project; the notice is in THIRD-PARTY-NOTICES.md):",
        "// decoder/ixheaacd_sbr_rom.c, esbr_qmf_c (31-bit integers, divided by 2^31) and common/ixheaac_esbr_rom.c, ixheaac_random_phase.",
        "namespace Encspect.Formats.Aac.Decoding;",
        "",
        "internal static class SbrTableData",
        "{",
        "    public static readonly float[] Qmf =",
        "    [",
        *lines_of(qmf(root)),
        "    ];",
        "",
        "    // Pairs of (real, imaginary).",
        "    public static readonly float[] Noise =",
        "    [",
        *lines_of(noise(root)),
        "    ];",
        "}",
    ]
    return "\n".join(out) + "\n"


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    text = render(Path(args[0]))
    if "--check" in sys.argv:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT} differs from what libxaac's tables give")
        print(f"{OUT.name} equals libxaac's tables")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
