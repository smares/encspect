#!/usr/bin/env python3
"""Writes src/Encspect.Formats.Wma/Tables.cs and ProTables.cs from FFmpeg 6.1.1's sources, so the Huffman tables of
Windows Media Audio are not typed in by hand:

    python3 scripts/fixtures/wma_tables.py            writes the file
    python3 scripts/fixtures/wma_tables.py --check    fails if the committed file differs

The sources are fetched by ffmpeg_sources.py (pinned by SHA-256). The tables are those of
libavcodec/wmadata.h (the six run-level coefficient codebooks with their level tables, the exponent
band sizes of 22.05, 32 and 44.1 kHz and the high-band gain codebook), wma_freqs.c (the critical
band frequencies) and aactab.c (the scalefactor codebook that the exponents of versions 1 and 2 share
with AAC). The line-spectral-pair codebook is not needed: the exponents only have to be skipped.
ProTables.cs holds the tables of libavcodec/wmaprodata.h that Windows Media Audio Professional
reads its scale factors, coefficients and vectors with.
VoiceTables.cs holds what libavcodec/wmavoice.c sizes a Windows Media Audio Voice frame with: the frame type descriptors, the code
lengths of the frame type VLC and the pitch-adaptive window's start offsets.
"""

import pathlib
import re
import sys
import tempfile

import ffmpeg_sources

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "Encspect.Formats.Wma" / "Tables.cs"
PRO_OUT = ROOT / "src" / "Encspect.Formats.Wma" / "ProTables.cs"
VOICE_OUT = ROOT / "src" / "Encspect.Formats.Wma" / "VoiceTables.cs"


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def array(text, name):
    """The numbers of the C array called name, flattened, with the count it declares."""
    match = re.search(r"\b" + re.escape(name) + r"\s*(\[[^\]]*\])+\s*=\s*\{(.*?)\n\};", text, flags=re.S)
    if match is None:
        raise SystemExit(f"{name} not found")
    body = match.group(2)
    values = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", body)]
    return values


def nested(text, name, width):
    """The rows of a two-dimensional C array, each padded with zeros to its declared width."""
    match = re.search(r"\b" + re.escape(name) + r"\s*(\[[^\]]*\])+\s*=\s*\{(.*?)\n\};", text, flags=re.S)
    if match is None:
        raise SystemExit(f"{name} not found")
    result = []
    for group in re.findall(r"\{([^{}]*)\}", match.group(2)):
        row = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", group)]
        result.append(row + [0] * (width - len(row)))
    return result


def literal(values, per_line, hexa=False):
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append("        " + ", ".join((f"0x{v:X}" if hexa else str(v)) for v in chunk) + ",")
    return "\n".join(lines)


def generate(source):
    data = strip_comments((source / "libavcodec" / "wmadata.h").read_text())
    freqs = strip_comments((source / "libavcodec" / "wma_freqs.c").read_text())
    aac = strip_comments((source / "libavcodec" / "aactab.c").read_text())

    out = []
    out.append("""// Generated by scripts/fixtures/wma_tables.py from FFmpeg 6.1.1 (libavcodec/wmadata.h, wma_freqs.c and
// aactab.c, SHA-256 8684f4b00f94b85461884c3719382f1261f0d9eb3d59640a1f4ac0873616f968); do not edit.
// The script's --check mode fails when this file differs from what it writes.
// Format data: the codebooks and band tables the WMA bitstream defines, no code (docs/development.md, "Where the format tables come from").
namespace Encspect.Formats.Wma;

internal static class Tables
{""")

    out.append("    // wma_freqs.c: the frequencies of the critical bands in Hz that version 1 divides the spectrum by.")
    out.append("    public static readonly ushort[] CriticalFrequencies =\n    [\n" + literal(array(freqs, "ff_wma_critical_freqs"), 8) + "\n    ];\n")

    for rate in ("22050", "32000", "44100"):
        values = nested(data, f"exponent_band_{rate}", 25)
        out.append(f"    // wmadata.h: exponent_band_{rate}: indexed by log2(block size) less 7: the number of bands and their sizes in coefficients.")
        out.append(f"    public static readonly byte[][] ExponentBands{rate} =\n    [")
        for row in values:
            out.append("        [" + ", ".join(str(v) for v in row) + "],")
        out.append("    ];\n")

    hgain = array(data, "ff_wma_hgain_hufftab")
    out.append("    // wmadata.h: ff_wma_hgain_hufftab: the high-band gain codebook as {symbol, code length} in code order; the code of\n"
               "    // each entry follows from the lengths (ff_vlc_init_from_lengths), and the value read is the symbol less 18.")
    out.append("    public static readonly byte[] HighBandGainSymbols =\n    [\n" + literal(hgain[0::2], 16) + "\n    ];\n")
    out.append("    public static readonly byte[] HighBandGainLengths =\n    [\n" + literal(hgain[1::2], 16) + "\n    ];\n")

    out.append("    // aactab.c: ff_aac_scalefactor_code and _bits: the codebook of the exponents of version 1 and 2; the value read\n"
               "    // is the index less 60.")
    out.append("    public static readonly uint[] ExponentCodes =\n    [\n" + literal(array(aac, "ff_aac_scalefactor_code"), 8, True) + "\n    ];\n")
    out.append("    public static readonly byte[] ExponentLengths =\n    [\n" + literal(array(aac, "ff_aac_scalefactor_bits"), 16) + "\n    ];\n")

    for index in range(6):
        codes = array(data, f"coef{index}_huffcodes")
        bits = array(data, f"coef{index}_huffbits")
        levels = array(data, f"levels{index}")
        assert len(codes) == len(bits)
        out.append(f"    // wmadata.h: coef{index}_huffcodes, coef{index}_huffbits and levels{index}: a run-level codebook of {len(codes)} codes.")
        out.append(f"    public static readonly uint[] Coefficient{index}Codes =\n    [\n" + literal(codes, 8, True) + "\n    ];\n")
        out.append(f"    public static readonly byte[] Coefficient{index}Lengths =\n    [\n" + literal(bits, 16) + "\n    ];\n")
        out.append(f"    public static readonly ushort[] Coefficient{index}Levels =\n    [\n" + literal(levels, 16) + "\n    ];\n")

    out.append("""    public static readonly uint[][] CoefficientCodes = [Coefficient0Codes, Coefficient1Codes, Coefficient2Codes, Coefficient3Codes, Coefficient4Codes, Coefficient5Codes];

    public static readonly byte[][] CoefficientLengths = [Coefficient0Lengths, Coefficient1Lengths, Coefficient2Lengths, Coefficient3Lengths, Coefficient4Lengths, Coefficient5Lengths];

    public static readonly ushort[][] CoefficientLevels = [Coefficient0Levels, Coefficient1Levels, Coefficient2Levels, Coefficient3Levels, Coefficient4Levels, Coefficient5Levels];
}""")
    return "\n".join(out) + "\n"


def pro_literal(name, kind, values, per_line, comment):
    return f"    // {comment}\n    public static readonly {kind}[] {name} =\n    [\n" + literal(values, per_line) + "\n    ];\n"


def generate_pro(source):
    text = strip_comments((source / "libavcodec" / "wmaprodata.h").read_text())
    out = ["""// Generated by scripts/fixtures/wma_tables.py from FFmpeg 6.1.1 (libavcodec/wmaprodata.h, SHA-256
// 8684f4b00f94b85461884c3719382f1261f0d9eb3d59640a1f4ac0873616f968); do not edit. The tables are
// the Huffman codebooks of Windows Media Audio Professional as {symbol, code length} pairs split in two
// arrays, or lengths and symbols, in code order: the code of each entry follows from the lengths
// (ff_vlc_init_from_lengths). The script's --check mode fails when this file differs from what it writes.
// Format data: the codebooks and band tables the WMA bitstream defines, no code (docs/development.md, "Where the format tables come from").
namespace Encspect.Formats.Wma;

internal static class ProTables
{"""]
    out.append(pro_literal("CriticalFrequencies", "ushort", array(text, "critical_freq"), 8, "critical_freq: the frequencies in Hz that divide the spectrum into scale factor bands."))
    for name, table, comment in (("Scale", "scale_table", "scale factors, DPCM-coded; the value read is the symbol less 60"),
                                 ("ScaleRl", "scale_rl_table", "scale factors, run-level coded"),
                                 ("Coefficient1", "coef1_table", "coefficients, run-level codebook 1"),
                                 ("Vector2", "vec2_table", "two vector-coded coefficients; the value read is the symbol less 1"),
                                 ("Vector1", "vec1_table", "one vector-coded coefficient")):
        rows = nested(text, table, 2)
        out.append(pro_literal(name + "Symbols", "byte" if name != "Coefficient1" else "ushort", [r[0] for r in rows], 16, f"{table}: the symbols of the codebook of {comment}."))
        out.append(pro_literal(name + "Lengths", "byte", [r[1] for r in rows], 16, f"{table}: the code lengths."))
    for name, lens, syms, comment in (("Coefficient0", "coef0_lens", "coef0_syms", "coefficients, run-level codebook 0"),
                                      ("Vector4", "vec4_lens", "vec4_syms", "four vector-coded coefficients; the value read is the symbol less 1")):
        out.append(pro_literal(name + "Symbols", "ushort", array(text, syms), 12, f"{syms}: the symbols of the codebook of {comment}."))
        out.append(pro_literal(name + "Lengths", "byte", array(text, lens), 16, f"{lens}: the code lengths."))
    out.append(pro_literal("ScaleRlRun", "byte", array(text, "scale_rl_run"), 16, "scale_rl_run: the run of each scale factor run-level code."))
    out.append(pro_literal("ScaleRlLevel", "byte", array(text, "scale_rl_level"), 16, "scale_rl_level: the level of each scale factor run-level code."))
    for index in (0, 1):
        out.append(pro_literal(f"Coefficient{index}Run", "ushort", array(text, f"coef{index}_run"), 16, f"coef{index}_run: the run of each coefficient code."))
        out.append(pro_literal(f"Coefficient{index}Level", "byte", array(text, f"coef{index}_level"), 16, f"coef{index}_level: the level of each coefficient code."))
    out.append("}")
    return "\n".join(out).rstrip("\n") + "\n"


def signed_array(text, name):
    """The numbers of the C array called name, negative ones too."""
    match = re.search(r"\b" + re.escape(name) + r"\s*(\[[^\]]*\])+\s*=\s*\{(.*?)\n\s*\};", text, flags=re.S)
    if match is None:
        raise SystemExit(f"{name} not found")
    return [int(v, 0) for v in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", match.group(2))]


def generate_voice(source):
    text = strip_comments((source / "libavcodec" / "wmavoice.c").read_text())
    match = re.search(r"frame_descs\[17\]\s*=\s*\{(.*?)\n\};", text, flags=re.S)
    if match is None:
        raise SystemExit("frame_descs not found")
    acb = {"ACB_TYPE_NONE": 0, "ACB_TYPE_ASYMMETRIC": 1, "ACB_TYPE_HAMMING": 2}
    fcb = {"FCB_TYPE_SILENCE": 0, "FCB_TYPE_HARDCODED": 1, "FCB_TYPE_AW_PULSES": 2, "FCB_TYPE_EXC_PULSES": 3}
    rows = []
    for group in re.findall(r"\{([^{}]*)\}", match.group(1)):
        n, log_n, acb_name, fcb_name, double_pulses = [v.strip() for v in group.split(",")]
        rows.append((int(n), int(log_n), acb[acb_name], fcb[fcb_name], int(double_pulses)))
    assert len(rows) == 17
    init = re.search(r"wmavoice_init_static_data\(void\)\s*\{(.*?)\n\}", text, flags=re.S)
    if init is None:
        raise SystemExit("wmavoice_init_static_data not found")
    lengths = signed_array(init.group(1), "bits")
    assert len(lengths) == 22
    offsets = signed_array(text, "start_offset")
    assert len(offsets) == 94
    # The writer of the hand-built fixtures (voice_model.py) keeps its own copy of these tables: it must be the source's.
    import voice_model
    if [tuple(r) for r in rows] != [tuple(r) for r in voice_model.FRAME_DESCRIPTORS] or lengths != voice_model.CODE_LENGTHS or offsets != voice_model.START_OFFSETS:
        raise SystemExit("voice_model.py's tables differ from wmavoice.c's")
    out = ["""// Generated by scripts/fixtures/wma_tables.py from FFmpeg 6.1.1 (libavcodec/wmavoice.c, SHA-256
// 8684f4b00f94b85461884c3719382f1261f0d9eb3d59640a1f4ac0873616f968); do not edit. The tables are what a frame of
// Windows Media Audio Voice is sized with. The script's --check mode fails when this file differs from what it writes.
// Format data: the codebooks and band tables the WMA bitstream defines, no code (docs/development.md, "Where the format tables come from").
namespace Encspect.Formats.Wma;

internal static class VoiceTables
{
    // wmavoice.c: frame_descs: for each of the 17 frame types its blocks per frame, the base-2 logarithm of that, its adaptive codebook
    // (0 none, 1 asymmetric window with a pitch per frame, 2 Hamming window with a pitch per block), its fixed codebook (0 silence,
    // 1 hardcoded, 2 pitch-adaptive window pulses, 3 pulse sets) and how many of the pulse set's five vectors hold a pulse pair.
    public static readonly byte[][] FrameDescriptors =
    [""" ]
    for row in rows:
        out.append("        [" + ", ".join(str(v) for v in row) + "],")
    out.append("    ];\n")
    out.append("    // wmavoice.c: wmavoice_init_static_data: the code lengths of the frame type VLC, in code order; the code of each follows from the\n"
               "    // lengths (ff_vlc_init_from_lengths) and the symbol is the index, which the frame type table of the codec data maps to a frame type.")
    out.append("    public static readonly byte[] FrameTypeCodeLengths =\n    [\n" + literal(lengths, 22) + "\n    ];\n")
    out.append("    // wmavoice.c: aw_parse_coords: start_offset, the offset of the first pitch-adaptive window pulse by the 6 or 8 bits read.")
    out.append("    public static readonly short[] StartOffsets =\n    [\n" + literal(offsets, 12) + "\n    ];\n}")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    with tempfile.TemporaryDirectory() as work:
        source = ffmpeg_sources.fetch(work)
        files = [(OUT, generate(source)), (PRO_OUT, generate_pro(source)), (VOICE_OUT, generate_voice(source))]
    if check:
        failed = False
        for path, text in files:
            if not path.exists() or path.read_text() != text:
                print(f"{path} differs from what the script writes from FFmpeg 6.1.1.")
                failed = True
            else:
                print(f"{path} agrees with FFmpeg 6.1.1.")
        return 1 if failed else 0
    for path, text in files:
        path.write_text(text)
        print(f"{path} written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
